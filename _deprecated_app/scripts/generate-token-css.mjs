#!/usr/bin/env node
// WDS 토큰 레지스트리 → 프로젝트용 CSS 변수/유틸 클래스를 생성한다.
// WDS의 theme.css는 색상(atomic/semantic)만 제공하므로, 여기선 누락된 것만 생성한다:
//   - spacing / opacity / breakpoint / z-index → CSS 변수
//   - typography variants → .wds-<variant> 유틸 클래스
//
// 출력: app/src/app/wds-tokens.css
// 실행: cd app && node scripts/generate-token-css.mjs
// 선행: scripts/generate-token-registry.mjs 로 레지스트리 최신화되어 있어야 함.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const REGISTRY = resolve(process.cwd(), "../registry/wds-token-registry.json");
const OUT_FILE = resolve(process.cwd(), "src/app/wds-tokens.css");

const r = JSON.parse(readFileSync(REGISTRY, "utf8"));
const { spacing, opacity, breakpoint, z_index, typography } = r.tiers;

const lines = [];
lines.push(
	"/* Auto-generated by app/scripts/generate-token-css.mjs — do not edit. */",
	"/* Source: registry/wds-token-registry.json */",
	"/* WDS theme.css 가 제공하지 않는 토큰(spacing/opacity/breakpoint/z-index)과 typography 유틸 클래스. */",
	"",
	":root {",
);

lines.push("\t/* spacing */");
for (const { key, px } of spacing.values) {
	const safeKey = key.replace(".", "\\."); // CSS needs `--spacing-0\.5`
	lines.push(`\t--spacing-${safeKey}: ${px};`);
}

lines.push("", "\t/* opacity */");
for (const [key, val] of Object.entries(opacity.values)) {
	lines.push(`\t--opacity-${key}: ${val};`);
}

lines.push("", "\t/* breakpoint */");
for (const [key, val] of Object.entries(breakpoint.values)) {
	lines.push(`\t--breakpoint-${key}: ${val};`);
}

lines.push("", "\t/* z-index */");
for (const [key, val] of Object.entries(z_index.values)) {
	lines.push(`\t--z-index-${key}: ${val};`);
}

lines.push("}", "");

lines.push(
	"/* typography — WDS Typography 컴포넌트와 동일한 스타일을 클래스로 노출. */",
	"/* 컴포넌트(<Typography variant=\"...\">) 우선 사용을 권장하며, 이 클래스는 컴포넌트 주입이 어려운 상황의 폴백이다. */",
	"",
);

for (const [name, spec] of Object.entries(typography.variants)) {
	lines.push(
		`.wds-${name} {`,
		`\tfont-size: ${spec.fontSize};`,
		`\tline-height: ${spec.lineHeight};`,
		`\tletter-spacing: ${spec.letterSpacing};`,
		"}",
		"",
	);
}

lines.push("/* typography weight modifiers */", "");
for (const [name, spec] of Object.entries(typography.weights)) {
	lines.push(`.wds-${name} {`, `\tfont-weight: ${spec.fontWeight};`, "}", "");
}

writeFileSync(OUT_FILE, lines.join("\n"));

const summary = [
	`${spacing.values.length} spacing`,
	`${Object.keys(opacity.values).length} opacity`,
	`${Object.keys(breakpoint.values).length} breakpoint`,
	`${Object.keys(z_index.values).length} z-index`,
	`${Object.keys(typography.variants).length} typography variants`,
	`${Object.keys(typography.weights).length} weights`,
].join(" · ");

console.log(`[wds-tokens.css] ${summary}`);
console.log(`→ ${OUT_FILE.replace(resolve(process.cwd(), "..") + "/", "")}`);
